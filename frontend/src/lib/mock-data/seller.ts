export function formatSellerPrice(value: number) {
  return new Intl.NumberFormat("tr-TR", {
    style: "currency",
    currency: "TRY",
    maximumFractionDigits: 0,
  }).format(value);
}

export function getPriorityProducts(limit = 3) {
  return [...sellerProducts]
    .sort((a, b) => b.aiRiskScore - a.aiRiskScore)
    .slice(0, limit);
}

export function getSellerProductById(id: string) {
  return sellerProducts.find((product) => product.id === id);
}

